import { writeFile, readFile } from "node:fs/promises";
import { createTestDatabase } from "./test-database.mjs";

// Generate from actual PostgreSQL catalogs, including composite relationships.
// No credentials or Docker needed. This reflects public-schema migrations only.
const db = await createTestDatabase();
try {
  const { rows: rpcs } = await db.query(`select p.proname as name, p.proargnames as names,
    array(select t.typname from unnest(p.proargtypes::oid[]) with ordinality a(id,n) join pg_type t on t.oid = a.id order by a.n) as types,
    r.typname as result, p.pronargdefaults as defaults, p.proretset as returns_set, p.proargmodes as modes
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type r on r.oid = p.prorettype
    where n.nspname = 'public' and p.prorettype <> 'trigger'::regtype order by p.proname`);
  const { rows: columns } = await db.query(`
    select c.table_name, c.column_name, c.is_nullable, c.column_default, c.data_type, c.udt_name
    from information_schema.columns c
    join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
    where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
    order by c.table_name, c.ordinal_position
  `);
  const { rows: enums } = await db.query(`
    select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as values
    from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' group by t.typname order by t.typname
  `);
  const { rows: relations } = await db.query(`
    select c.conname as name, s.relname as source, t.relname as target,
      array(select a.attname from unnest(c.conkey) with ordinality k(id, n)
        join pg_attribute a on a.attrelid = c.conrelid and a.attnum = k.id order by k.n) as columns,
      array(select a.attname from unnest(c.confkey) with ordinality k(id, n)
        join pg_attribute a on a.attrelid = c.confrelid and a.attnum = k.id order by k.n) as referenced_columns,
      exists(select 1 from pg_constraint u where u.conrelid = c.conrelid and u.contype in ('p', 'u') and u.conkey = c.conkey) as one_to_one
    from pg_constraint c join pg_class s on s.oid = c.conrelid join pg_namespace n on n.oid = s.relnamespace
      join pg_class t on t.oid = c.confrelid
    where c.contype = 'f' and n.nspname = 'public' order by s.relname, c.conname
  `);
  function typeFor(column) {
    if (enums.some((item) => item.name === column.udt_name)) return `Database["public"]["Enums"][${JSON.stringify(column.udt_name)}]`;
    const types = { uuid: "string", text: "string", timestamptz: "string", bool: "boolean", int4: "number", int8: "number", jsonb: "Json", void: "undefined" };
    if (!types[column.udt_name]) throw new Error(`Add a type mapping for ${column.udt_name}`);
    return types[column.udt_name];
  }
  const lines = [
    "// Generated by npm run db:types from migrations. Do not edit by hand.",
    'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];',
    "export type Database = {", "  public: {", "    Tables: {",
  ];
  for (const table of [...new Set(columns.map((column) => column.table_name))]) {
    lines.push(`      ${table}: {`);
    for (const mode of ["Row", "Insert", "Update"]) {
      lines.push(`        ${mode}: {`);
      for (const column of columns.filter((item) => item.table_name === table)) {
        const optional = mode === "Update" || (mode === "Insert" && (column.column_default !== null || column.is_nullable === "YES"));
        lines.push(`          ${column.column_name}${optional ? "?" : ""}: ${typeFor(column)}${column.is_nullable === "YES" ? " | null" : ""};`);
      }
      lines.push("        };");
    }
    lines.push("        Relationships: [");
    for (const relation of relations.filter((item) => item.source === table)) {
      lines.push(`          { foreignKeyName: ${JSON.stringify(relation.name)}; columns: ${JSON.stringify(relation.columns)}; isOneToOne: ${relation.one_to_one}; referencedRelation: ${JSON.stringify(relation.target)}; referencedColumns: ${JSON.stringify(relation.referenced_columns)} },`);
    }
    lines.push("        ];", "      };");
  }
  lines.push("    };", "    Views: Record<never, never>;", "    Functions: {");
  for (const rpc of rpcs) {
    if (rpc.modes || rpc.returns_set) throw new Error(`Extend RPC type generation for ${rpc.name}`);
    // PostgreSQL catalogs do not describe parameter nullability. This RPC explicitly
    // uses a null group ID to select creation rather than editing.
    const args = rpc.names.map((name, i) => `${name}${i >= rpc.names.length - rpc.defaults ? "?" : ""}: ${typeFor({ udt_name: rpc.types[i] })}${rpc.name === "save_group" && name === "p_group_id" ? " | null" : ""}`).join("; ");
    lines.push(`      ${rpc.name}: { Args: { ${args} }; Returns: ${typeFor({ udt_name: rpc.result })} };`);
  }
  lines.push("    };", "    Enums: {");
  for (const item of enums) lines.push(`      ${item.name}: ${item.values.map((value) => JSON.stringify(value)).join(" | ")};`);
  lines.push("    };", "    CompositeTypes: Record<never, never>;", "  };", "};", "");
  const output = lines.join("\n");
  const target = new URL("../lib/supabase/database.types.ts", import.meta.url);
  if (process.argv.includes("--check")) {
    if (await readFile(target, "utf8") !== output) throw new Error("Database types are stale. Run npm run db:types.");
    console.log("Database types match the migrated PostgreSQL schema.");
  } else {
    await writeFile(target, output);
    console.log("Generated database types from migrated PostgreSQL catalogs.");
  }
} finally { await db.close(); }
